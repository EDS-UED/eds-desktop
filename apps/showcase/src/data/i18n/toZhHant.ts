export function toZhHant(text: string): string {
  let result = text;
  const phrases = Object.keys(SIMPLIFIED_TO_TRADITIONAL).sort((a, b) => b.length - a.length);
  for (const phrase of phrases) {
    result = result.split(phrase).join(SIMPLIFIED_TO_TRADITIONAL[phrase]!);
  }
  return result;
}
